#!/usr/bin/env bash
# purge-to-legacy.sh · 把 dead-code 候选移到 _legacy/<UTC>/，保留原路径 + 写 README + 全局日志
#
# 用法:
#   purge-to-legacy [-r|--reason "<原因>"] <file1> [<file2> ...]
#
# 行为:
#   - 在项目根（找最近的 git root，或 PWD）创建 _legacy/<UTC-date>/
#   - 优先 git mv（保留历史），fallback 普通 mv
#   - 写 _legacy/<UTC>/README.md 含清理理由 + 文件清单 + dead-code-report 链接
#   - 全局日志: $HOME/.codex/logs/purge-to-legacy/<UTC>.log
#   - 永远不删，永远人审通过才会调

set -euo pipefail

REASON=""
FILES=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    -r|--reason)
      if [[ $# -lt 2 ]]; then
        echo "ERR: --reason 需要参数" >&2
        exit 2
      fi
      REASON="$2"
      shift 2
      ;;
    -h|--help)
      cat <<EOF
purge-to-legacy.sh — 安全移除死代码到 _legacy/

  -r, --reason <text>   清理理由（写到 _legacy README）
  <file>...             要移除的文件（支持多个）

不会删除任何东西。所有文件 git mv 到 _legacy/<UTC>/<orig-path>。
EOF
      exit 0;;
    *) FILES+=("$1"); shift;;
  esac
done

if [[ ${#FILES[@]} -eq 0 ]]; then
  echo "ERR: 至少给 1 个文件" >&2
  exit 2
fi

# 找项目根（git root 优先，否则 PWD）
PROJECT_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$PROJECT_ROOT" || exit 2
PROJECT_ROOT_ABS="$(readlink -f "$PROJECT_ROOT")"

EXISTING_COUNT=0
for F in "${FILES[@]}"; do
  if [[ ! -e "$F" ]]; then
    continue
  fi
  EXISTING_COUNT=$((EXISTING_COUNT+1))
  ABS_F="$(readlink -f "$F")"
  case "$ABS_F" in
    "$PROJECT_ROOT_ABS"/*) ;;
    *)
      echo "ERR: 项目外路径禁止 purge: $F" >&2
      exit 2
      ;;
  esac
done

if [[ $EXISTING_COUNT -eq 0 ]]; then
  echo "ERR: 没有可移动的现有文件" >&2
  exit 2
fi

UTC="$(date -u +'%Y-%m-%dT%H-%M-%SZ')"
LEGACY_DIR="$PROJECT_ROOT/_legacy/$UTC"
README="$LEGACY_DIR/README.md"
LOG_DIR="$HOME/.codex/logs/purge-to-legacy"
mkdir -p "$LOG_DIR"
LOG_FILE="$LOG_DIR/${UTC}.log"

# 全部输出 tee 到日志
exec > >(tee -a "$LOG_FILE") 2>&1

echo "=== purge-to-legacy ==="
echo "started:      $(date -u +'%Y-%m-%dT%H:%M:%SZ')"
echo "project root: $PROJECT_ROOT"
echo "legacy dir:   _legacy/$UTC/"
echo "reason:       ${REASON:-_(no reason provided)_}"
echo "log:          $LOG_FILE"
echo "files:        ${#FILES[@]}"
echo

mkdir -p "$LEGACY_DIR"

# 写 README
{
  echo "# Legacy Purge: $UTC"
  echo
  echo "**Reason**: ${REASON:-_(none)_}"
  echo
  echo "## Files moved"
  echo
  for F in "${FILES[@]}"; do
    REL="${F#./}"
    REL="${REL#$PROJECT_ROOT/}"
    echo "- \`$REL\`"
  done
  echo
  echo "## Source dead-code reports"
  echo
  if [[ -f "_wiki-methodology/_top/_reports/_dead_code/dead-code-report.md" ]]; then
    echo "- [\`_wiki-methodology/_top/_reports/_dead_code/dead-code-report.md\`](../../_wiki-methodology/_top/_reports/_dead_code/dead-code-report.md)"
  elif [[ -f "top/dead-code-report.md" ]]; then
    echo "- [\`top/dead-code-report.md\`](../../top/dead-code-report.md)"
  elif [[ -f ".audit-rot/report.md" ]]; then
    echo "- [\`.audit-rot/report.md\`](../../.audit-rot/report.md)"
  else
    echo "- _(无报告，纯人工判定)_"
  fi
  echo
  echo "## Rollback"
  echo
  echo "\`\`\`bash"
  echo "# 在项目根跑："
  echo "git mv _legacy/$UTC/* ./"
  echo "git rm -rf _legacy/$UTC/"
  echo "\`\`\`"
  echo
  echo "## Why these were moved (复审标准)"
  echo
  echo "- audit-rot 在报告里标了候选"
  echo "- AI 已逐个确认 _不_ 是动态 import / 反射 / 装饰器注册 / CLI 入口 / pytest fixture"
  echo "- 用户已批准（本脚本只在用户显式同意时调）"
  echo
  echo "_generated by $HOME/.claude/skills/share-top/scripts/purge-to-legacy.sh_"
} > "$README"

# 移动文件
USE_GIT=0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 && USE_GIT=1

MOVED=0
SKIPPED=0
for F in "${FILES[@]}"; do
  if [[ ! -e "$F" ]]; then
    echo "  [SKIP] $F (不存在)"
    SKIPPED=$((SKIPPED+1))
    continue
  fi
  REL="${F#./}"
  REL="${REL#$PROJECT_ROOT/}"
  TARGET="$LEGACY_DIR/$REL"
  mkdir -p "$(dirname "$TARGET")"

  if [[ $USE_GIT -eq 1 ]] && git ls-files --error-unmatch "$F" >/dev/null 2>&1; then
    if git mv "$F" "$TARGET" 2>/dev/null; then
      echo "  [git mv] $REL"
      MOVED=$((MOVED+1))
    else
      mv "$F" "$TARGET" && echo "  [mv]     $REL (git mv 失败 fallback)"
      MOVED=$((MOVED+1))
    fi
  else
    mv "$F" "$TARGET" && echo "  [mv]     $REL"
    MOVED=$((MOVED+1))
  fi
done

echo
echo "汇总: 移除 $MOVED, 跳过 $SKIPPED"
echo "ended:   $(date -u +'%Y-%m-%dT%H:%M:%SZ')"
echo
echo "下一步:"
echo "  1) 跑 audit-rot 刷新报告"
echo "  2) 跑测试确认没事"
echo "  3) 没事 → git commit"
echo "  4) 出问题 → 看 _legacy/$UTC/README.md 末尾的 rollback 块"
